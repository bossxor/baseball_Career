import assert from 'node:assert/strict';
import test from 'node:test';
import { createKboClubGame } from '../src/kbo-club-game.js';
import { clubEraLabel, clubInternationalWindows, clubMilitaryWatch, clubStrategyReport, enlistClubMilitary, initialClubStrategy, nextClubStrategy, returnClubMilitary } from '../src/kbo-club-labels.js';
import { completeSangmuBlock } from '../src/kbo-military-program.js';
import { kboMilitaryCompletionDays } from '../src/kbo-military-events.js';
import { kboClubRosterIssues } from '../src/kbo-club-game.js';

test('strategy labels, sangmu enlistment and international windows', () => {
  assert.equal(nextClubStrategy('BALANCED', [], null), 'BALANCED');
  assert.equal(nextClubStrategy('BALANCED', [1], 30), 'CONTEND');
  assert.equal(nextClubStrategy('CONTEND', [8, 9], 28), 'DEVELOPMENT');
  assert.equal(nextClubStrategy('DEVELOPMENT', [5], 30), 'BALANCED');
  assert.equal(clubEraLabel([{ rank: 1, postseason: true, winRate: 0.6 }, { rank: 2, postseason: false, winRate: 0.5 }]), 'EVALUATING');
  assert.equal(clubEraLabel([{ rank: 8, postseason: false, winRate: 0.4 }, { rank: 9, postseason: false, winRate: 0.4 }, { rank: 10, postseason: false, winRate: 0.3 }]), 'SLUMP');
  assert.equal(clubEraLabel([{ rank: 1, postseason: true, winRate: 0.6 }, { rank: 2, postseason: true, winRate: 0.6 }, { rank: 4, postseason: false, winRate: 0.6 }]), 'PEAK');
  const game = createKboClubGame({ worldKey: 'labels', seed: 'm6i', clubId: 'LG', difficulty: 'REALISTIC' });
  const before = game.world.clubs.find(club => club.id === 'LG')!.roster.length;
  const report = clubStrategyReport(game.world);
  assert.equal(report.length, 10);
  assert.equal(report.find(row => row.clubId === 'LG')?.strategy, initialClubStrategy(game.world.seed, game.world.worldKey, 'LG'));
  assert.equal(report.every(row => row.era === 'EVALUATING'), true);
  const watch = clubMilitaryWatch(game);
  assert.ok(watch.mine.length <= 3);
  assert.equal(game.world.clubs.find(club => club.id === 'LG')!.roster.length, before);
  assert.deepEqual(clubInternationalWindows(game), game.world.calendar.international.map(window => ({ type: window.type, startDay: window.startDay, endDay: window.endDay })));
  const enlisted = enlistClubMilitary(game, game.revision);
  assert.equal(enlisted.sangmu?.enlistedSeasons[0], game.world.seasonKey);
  assert.ok(Object.keys(enlisted.sangmu?.members ?? {}).length > 0);
  for (const key of Object.keys(enlisted.sangmu?.members ?? {})) assert.equal(enlisted.world.players[key], undefined);
  assert.equal(kboClubRosterIssues(enlisted).filter(issue => issue !== 'FIRST_TEAM_INJURED').length, 0);
  assert.equal(clubMilitaryWatch(enlisted).enlisted, true);
  assert.throws(() => enlistClubMilitary(enlisted, enlisted.revision), /SANGMU_COHORT_ALREADY_ENLISTED/);
  assert.throws(() => returnClubMilitary(enlisted, enlisted.revision), /SANGMU_RETURN_NOT_DUE/);
  const key = Object.keys(enlisted.sangmu!.members)[0]!;
  const days = kboMilitaryCompletionDays(enlisted.sangmu!.members[key]!.program);
  let program = enlisted.sangmu!.members[key]!.program;
  program = completeSangmuBlock(program, days[0]!.seasonKey, days[0]!.worldDay);
  program = completeSangmuBlock(program, days[1]!.seasonKey, days[1]!.worldDay);
  const ready = structuredClone(enlisted);
  const member = ready.sangmu!.members[key]!;
  ready.sangmu = { ...ready.sangmu!, members: { ...ready.sangmu!.members, [key]: { ...member, program } } };
  ready.world.seasonKey = days[1]!.seasonKey;
  const back = returnClubMilitary(ready, ready.revision);
  const home = back.world.clubs.find(club => club.id === program.originalClubId)!;
  assert.equal(home.roster.includes(key), true);
  assert.equal(home.firstTeam.includes(key), false);
  assert.equal(back.sangmu!.members[key], undefined);
});
